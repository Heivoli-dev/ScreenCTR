#!/usr/bin/env python3
"""Generate console/source/font.h: an 8x12 1-bit font rendered from
DejaVu Sans Mono (Bitstream Vera licence, redistributable) for the console
overlay. Covers ASCII 32..126 plus French accented letters (Latin-1)."""
import sys
from PIL import Image, ImageDraw, ImageFont

TTF = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
OUT = sys.argv[2] if len(sys.argv) > 2 else "console/source/font.h"
W, H = 8, 12
chars = [chr(c) for c in range(32, 127)] + list("éèêëàâçùûôîïÉÈÀÇ°")
font = ImageFont.truetype(TTF, 11)

rows = []
for ch in chars:
    img = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(img)
    d.text((0, -1), ch, font=font, fill=255)
    bits = []
    for y in range(H):
        b = 0
        for x in range(W):
            if img.getpixel((x, y)) >= 110:
                b |= 0x80 >> x
        bits.append(b)
    rows.append((ch, bits))

with open(OUT, "w", encoding="utf-8") as f:
    f.write("/* Generated by tools/gen_font.py from DejaVu Sans Mono — do not edit.\n"
            " * DejaVu fonts: Bitstream Vera licence (free redistribution). */\n")
    f.write("#pragma once\n#include <stdint.h>\n")
    f.write(f"#define FONT_W {W}\n#define FONT_H {H}\n#define FONT_COUNT {len(rows)}\n")
    f.write("/* Unicode code point of each glyph, in table order */\n")
    f.write("static const uint16_t font_cp[FONT_COUNT] = {" + ",".join(str(ord(c)) for c, _ in rows) + "};\n")
    f.write("static const uint8_t font_bits[FONT_COUNT][FONT_H] = {\n")
    for c, bits in rows:
        f.write("  {" + ",".join(f"0x{b:02X}" for b in bits) + "}, /* U+%04X */\n" % ord(c))
    f.write("};\n")
print(f"wrote {len(rows)} glyphs to {OUT}")
